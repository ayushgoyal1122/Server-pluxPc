export async function seedInitialBlogs(force = false) {
  try {
    const existingCount = await Blog.countDocuments();
    if (existingCount > 0 && !force) {
      console.log(`[Seed Blogs]: Blog collection already contains ${existingCount} article(s). Skipping seed.`);
      return;
    }

    if (force && existingCount > 0) {
      console.log(`[Seed Blogs]: Force mode enabled. Replacing existing blog posts with updated Consumer Electronics articles...`);
      await Blog.deleteMany({});
    }

    console.log(`[Seed Blogs]: Initializing ${SAMPLE_BLOGS.length} Consumer Electronics & Gadget articles...`);
    await Blog.insertMany(SAMPLE_BLOGS);
    console.log(`[Seed Blogs]: Successfully seeded ${SAMPLE_BLOGS.length} Consumer Electronics articles into MongoDB.`);
  } catch (err) {
    console.error('[Seed Blogs Error]:', err.message);
  }
}
